test('the registered demo host saves a checkpoint across reload and restores it', async ({ page }) => {
  await page.goto('/test/workbook.html')
  await cell(page, '1:1').click()
  const bar = page.getByRole('textbox', { name: '公式栏' })
  await bar.fill('914')
  await bar.press('Enter')
  await button(page, '版本历史').click()
  const history = page.getByRole('dialog', { name: '版本历史' })
  await expect(history.getByRole('status')).toHaveText('暂无版本')
  await history.getByLabel('版本说明').fill('重要版本')
  await history.getByRole('button', { name: '保存版本' }).click()
  await expect(history.getByRole('listitem')).toContainText('重要版本')
  await history.getByRole('button', { name: '关闭' }).click()
  await cell(page, '1:1').click()
  await bar.fill('990')
  await bar.press('Enter')
  await button(page, '版本历史').click()
  await history.getByLabel('版本说明').fill('对比版本')
  await history.getByRole('button', { name: '保存版本' }).click()
  await expect(history.getByRole('listitem')).toHaveCount(2)
  await page.reload()
  await expect(value(page, '1:1')).toHaveText('240')
  await button(page, '版本历史').click()
  const historical = history.getByRole('listitem').filter({ hasText: '重要版本' })
  await expect(historical).toBeVisible()
  const preview = history.getByRole('region', { name: '版本差异' })
  await history.getByRole('button', { name: '预览 重要版本' }).click()
  await expect(preview.getByRole('row', { name: 'B2 240 914' })).toBeVisible()
  await expect(value(page, '1:1')).toHaveText('240')
  const baseline = history.getByLabel('对比基准', { exact: true })
  const previousId = await baseline.locator('option').filter({ hasText: '对比版本' }).getAttribute('value')
  await baseline.selectOption(previousId)
  await historical.getByRole('button', { name: '预览 重要版本' }).click()
  await expect(preview.getByRole('row', { name: 'B2 990 914' })).toBeVisible()
  page.once('dialog', dialog => dialog.accept())
  await historical.getByRole('button', { name: '恢复' }).click()
  await expect(history.getByRole('status')).toHaveText('')
  await history.getByRole('button', { name: '关闭' }).click()
  await expect(value(page, '1:1')).toHaveText('914')
})
