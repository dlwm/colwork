import { test, expect } from '@playwright/test'

const cell = (page, key) => page.locator(`td[data-key="${key}"]`)
const value = (page, key) => cell(page, key).locator('.colwork-table__cell-value')
const button = (page, name) => page.getByRole('button', { name, exact: true })

async function mount(page) {
  await page.goto('/test/e2e/fixture.html')
  await page.evaluate(async () => {
    const { ColworkTable, getSheetMaps } = await import('/src/index.ts')
    const { Y, Awareness } = await import('/test/e2e/external-fixture.ts')
    const doc = new Y.Doc()
    const maps = getSheetMaps(doc)
    window.model = doc
    const awareness = new Awareness(doc)
    let instance
    window.mountTable = () => {
      instance?.destroy()
      instance = window.table = new ColworkTable(document.querySelector('#table'), {
        user: 'editor', transport: 'external', collaboration: { document: doc, awareness },
        personalViewKey: 'tools-test',
      })
    }
    doc.transact(() => {
      for (const [key, text] of Object.entries({ '0:0': 'Name', '0:1': 'Amount', '1:0': 'Alpha', '1:1': '2', '2:0': 'Beta', '2:1': '4', '3:0': 'Alpha' })) maps.cells.set(key, text)
    })
    mountTable()
  })
}

test('keyboard navigation, formula bar, search and the fill handle write to shared cells', async ({ page }) => {
  await mount(page)
  await cell(page, '1:1').click()
  await page.keyboard.press('ArrowRight')
  const bar = page.getByRole('textbox', { name: '公式栏' })
  await bar.fill('=B2*2')
  await bar.press('Enter')
  await expect(value(page, '1:2')).toHaveText('4')
  await page.keyboard.press('Shift+ArrowDown')
  expect(await page.evaluate(() => table.selection.getSelectionBounds())).toMatchObject({ top: 1, bottom: 2, left: 2 })
  await cell(page, '1:2').click()
  const handle = await cell(page, '1:2').locator('.colwork-table__fill-handle').boundingBox()
  const target = await cell(page, '2:2').boundingBox()
  await page.mouse.move(handle.x + handle.width / 2, handle.y + handle.height / 2)
  await page.mouse.down()
  await page.mouse.move(target.x + target.width / 2, target.y + target.height / 2)
  await page.mouse.up()
  await expect(value(page, '2:2')).toHaveText('8')
  await cell(page, '1:0').click()
  await page.keyboard.press('Control+f')
  await page.getByRole('textbox', { name: '查找内容' }).fill('Alpha')
  await button(page, '查找下一项').click()
  await expect(page.getByRole('dialog', { name: '查找替换' }).getByRole('status')).toHaveText('1 / 2')
  await page.getByRole('textbox', { name: '替换为' }).fill('Gamma')
  await button(page, '全部替换文本').click()
  await button(page, '关闭').click()
  await expect(value(page, '1:0')).toHaveText('Gamma')
  await expect(value(page, '3:0')).toHaveText('Gamma')
})

test('personal views restore merged row groups and rules remain attached to their source rows', async ({ page }) => {
  await mount(page)
  await page.evaluate(() => {
    model.getMap('merges').set('1:0-2:0', '1')
    model.getMap('colwork-validation').set('1:1-2:1', JSON.stringify({ choices: ['2', '4'] }))
    table.setRowView({ sort: { column: 1, direction: 'desc' }, filters: [{ column: 1, contains: '4' }], headerRows: 1 })
  })
  await expect(cell(page, '1:0')).toHaveAttribute('rowspan', '2')
  await expect(value(page, '1:0')).toHaveText('Alpha')
  await expect(cell(page, '3:0')).toHaveCount(0)
  await page.evaluate(() => mountTable())
  await expect(cell(page, '1:0')).toHaveAttribute('rowspan', '2')
  await cell(page, '2:1').click()
  await button(page, '选择选项').click()
  await button(page, '2').click()
  expect(await page.evaluate(() => model.getMap('cells').get('2:1'))).toBe('2')
  await expect(cell(page, '1:0')).toHaveCount(0)
})

test('drop-down validation, conditional formatting and a saved pivot work in the editor', async ({ page }) => {
  await mount(page)
  await cell(page, '3:1').click()
  await button(page, '数据').click()
  await button(page, '数据验证').click()
  await page.getByLabel('选项列表', { exact: true }).fill('8\n16')
  await button(page, '设置下拉选项').click()
  await button(page, '选择选项').click()
  await button(page, '8').click()
  await expect(value(page, '3:1')).toHaveText('8')
  const bar = page.getByRole('textbox', { name: '公式栏' })
  await bar.fill('9')
  await bar.press('Enter')
  await expect(page.getByRole('alertdialog')).toContainText('数据验证')
  await button(page, '确定').click()
  await expect(value(page, '3:1')).toHaveText('8')

  await page.evaluate(() => table.selection.selectRange({ row: 1, column: 1 }, { row: 3, column: 1 }))
  await button(page, '数据').click()
  await button(page, '条件格式').click()
  await page.getByLabel('匹配条件').selectOption('greater')
  await page.getByLabel('比较值').fill('3')
  await button(page, '保存条件格式').click()
  await expect(value(page, '2:1')).toHaveCSS('background-color', 'rgb(254, 243, 199)')

  await page.evaluate(() => table.selection.selectRange({ row: 0, column: 0 }, { row: 3, column: 1 }))
  await button(page, '数据').click()
  await button(page, '图表与数据透视').click()
  await page.getByLabel('分析类型').selectOption('pivot')
  await page.getByLabel('分析名称').fill('项目透视')
  await button(page, '保存分析').click()
  await button(page, '数据').click()
  await button(page, '图表与数据透视').click()
  await page.getByLabel('已保存分析').selectOption({ label: '项目透视' })
  await expect(page.getByRole('dialog').getByRole('row', { name: 'Alpha 10' })).toBeVisible()
})

test('the registered demo host saves a checkpoint across reload and restores it', async ({ page }) => {
  await page.goto('/test/workbook.html')
  await cell(page, '1:1').click()
  const bar = page.getByRole('textbox', { name: '公式栏' })
  await bar.fill('914')
  await bar.press('Enter')
  await button(page, '版本历史').click()
  const history = page.getByRole('dialog', { name: '版本历史' })
  await expect(history.getByRole('status')).toHaveText('暂无版本')
  await history.getByLabel('版本说明').fill('重要版本')
  await history.getByRole('button', { name: '保存版本' }).click()
  await expect(history.getByRole('listitem')).toContainText('重要版本')
  await page.reload()
  await expect(value(page, '1:1')).toHaveText('240')
  await button(page, '版本历史').click()
  await expect(history.getByRole('listitem')).toContainText('重要版本')
  page.once('dialog', dialog => dialog.accept())
  await history.getByRole('button', { name: '恢复' }).click()
  await expect(history.getByRole('status')).toHaveText('')
  await history.getByRole('button', { name: '关闭' }).click()
  await expect(value(page, '1:1')).toHaveText('914')
})
